"""Run on Modal: one deployed app per project, one function per plan, results on a Modal volume.

The app is generated from testbench.yaml into .testbench/modal_app.py (readable, not hand-edited), deployed, and
the plan's function is spawned, so the run keeps going if this machine sleeps or loses its network. Lessons
built in:
  - the function's timeout is the plan's budget, so the worst case holds on Modal's side;
  - CPU and memory are always explicit (a GPU function without cpu= gets one core, and the GPU waits on it);
  - no retries and a 2-second scaledown, so a finished or failed run stops billing at once;
  - local files are added as the image's last steps, so editing code does not rebuild the image.
"""
from __future__ import annotations

import json
import subprocess
import sys
import textwrap
import threading
import time
from pathlib import Path

from .. import budget

APP_TEMPLATE = '''\
# Generated by agent-testbench from testbench.yaml - edit testbench.yaml, not this file. Regenerated on every Modal run.
import json
import threading
import time
from pathlib import Path

import modal

app = modal.App({app_name!r})
volume = modal.Volume.from_name({volume_name!r}, create_if_missing=True)
image = (
    modal.Image.debian_slim(python_version={python!r})
{image_steps}
    .add_local_python_source("agent_testbench")
    .add_local_dir({root!r}, "/project", ignore={ignore!r})
)


def _run(run_id: str, plan: dict, meta: dict) -> dict:
    import os
    import shutil
    from agent_testbench.executor import execute_plan

    work = Path("/work/project")
    shutil.copytree("/project", work, dirs_exist_ok=True, symlinks=True)
    if not Path("/content").exists():          # Colab notebooks expect to live in /content
        Path("/content").symlink_to(work)
    os.environ["TESTBENCH_CACHE"] = "/testbench/cache"
    Path("/testbench/cache").mkdir(parents=True, exist_ok=True)
    run_dir = Path("/testbench/runs") / run_id
    stop = threading.Event()

    def keep_committing():                      # live logs reach the volume about once a minute
        while not stop.wait(60):
            try:
                volume.commit()
            except Exception:
                pass

    threading.Thread(target=keep_committing, daemon=True).start()
    try:
        report = execute_plan(plan, project_dir=work, run_dir=run_dir, workdir=work, meta=meta, on_progress=volume.commit)
    finally:
        stop.set()
        volume.commit()
    return {{"status": report["status"], "minutes": report.get("minutes")}}
{functions}
'''

FUNCTION_TEMPLATE = '''

@app.function(image=image, gpu={gpu!r}, cpu={cpu!r}, memory={memory!r}, timeout={timeout!r}, retries=0,
              scaledown_window=2, volumes={{"/testbench": volume}}, secrets=[{secrets}])
def {fn}(run_id: str, plan: dict, meta: dict) -> dict:
    return _run(run_id, plan, meta)
'''


def app_name(cfg: dict) -> str:
    return f"testbench-{cfg['project']}"


def fn_name(plan_name: str) -> str:
    return "plan_" + "".join(c if c.isalnum() else "_" for c in plan_name)


def generate(cfg: dict) -> str:
    m = cfg["modal"]
    steps = []
    if m.get("apt"):
        steps.append(f"    .apt_install({', '.join(repr(x) for x in m['apt'])})")
    base = ["nbformat>=5.9", "nbclient>=0.10", "ipykernel>=6.29", "pyyaml>=6"]
    uses_web = any(s["kind"] == "web" for p in cfg["plans"].values() if p["backend"] == "modal" for s in p["steps"])
    if uses_web:
        base.append("playwright>=1.45")
    steps.append(f"    .pip_install({', '.join(repr(x) for x in base + list(m.get('pip') or []))})")
    if m.get("requirements"):
        req = Path(cfg["root"]) / m["requirements"]
        steps.append(f"    .pip_install_from_requirements({str(req)!r})")
    if uses_web:
        steps.append('    .run_commands("playwright install --with-deps chromium")')
    for cmd in m.get("run_commands") or []:
        steps.append(f"    .run_commands({cmd!r})")
    ignore = []
    for p in list(cfg["exclude"]) + [".testbench"]:
        ignore += [p] if "/" in p else [p, f"**/{p}"]
    functions = []
    for name, plan in cfg["plans"].items():
        if plan["backend"] != "modal":
            continue
        minutes = sum(s["max_minutes"] for s in plan["steps"])
        secrets = sorted({s for st in plan["steps"] for s in st["secrets"]})
        functions.append(FUNCTION_TEMPLATE.format(
            gpu=plan.get("gpu"), cpu=float(plan.get("cpu", m["cpu"])), memory=int(float(plan.get("memory_gb", m["memory_gb"])) * 1024),
            timeout=int((minutes + 3) * 60), fn=fn_name(name),
            secrets=", ".join(f"modal.Secret.from_name({s!r})" for s in secrets)))
    return APP_TEMPLATE.format(app_name=app_name(cfg), volume_name=app_name(cfg), python=str(m["python"]),
                               image_steps="\n".join(steps), root=str(cfg["root"]), ignore=ignore,
                               functions="".join(functions))


def cancel_call(call_id: str) -> str:
    import modal
    try:
        modal.FunctionCall.from_id(call_id).cancel(terminate_containers=True)
        return f"Modal call {call_id} cancelled"
    except Exception as exc:
        return f"could not cancel Modal call {call_id}: {exc}"


class ModalBackend:
    def __init__(self, root: Path, cfg: dict, run_dir: Path, plan: dict, meta: dict):
        self.root, self.cfg, self.run_dir, self.plan, self.meta = Path(root), cfg, Path(run_dir), plan, meta
        self.call = None
        self.remote_started = None
        self._seen: dict[str, tuple] = {}

    def _log(self, text: str) -> None:
        print(f"[testbench] {text}", flush=True)

    def deploy(self) -> None:
        app_file = self.root / ".testbench" / "modal_app.py"
        app_file.parent.mkdir(parents=True, exist_ok=True)
        app_file.write_text(generate(self.cfg))
        self._log(f"deploying {app_name(self.cfg)} from {app_file}")
        proc = subprocess.run([sys.executable, "-m", "modal", "deploy", str(app_file)], cwd=self.root,
                              capture_output=True, text=True, timeout=1800)
        (self.run_dir / "modal_deploy.log").write_text(proc.stdout + proc.stderr)
        if proc.returncode != 0:
            tail = "\n".join((proc.stdout + proc.stderr).strip().splitlines()[-25:])
            raise RuntimeError(f"`modal deploy` failed (is Modal set up? run `modal setup`):\n{tail}")

    def run(self):
        import modal
        from .. import runs
        self.deploy()
        fn = modal.Function.from_name(app_name(self.cfg), fn_name(self.meta["plan"]))
        self.call = fn.spawn(self.run_dir.name, self.plan, self.meta)
        self.remote_started = time.time()
        runs.write_state(self.run_dir, modal_call_id=self.call.object_id, modal_app=app_name(self.cfg))
        self._log(f"spawned Modal call {self.call.object_id}")
        volume = modal.Volume.from_name(app_name(self.cfg))
        result = None
        while True:
            try:
                result = self.call.get(timeout=20)
                break
            except (TimeoutError, modal.exception.TimeoutError):
                self._mirror(volume, light=True)
            except modal.exception.FunctionTimeoutError:
                result = {"status": "timeout"}
                break
        self._mirror(volume, light=False)
        from .. import report as R
        rep = R.load(self.run_dir) or {**self.meta, "steps": [], "started": self.remote_started, "status": "error"}
        if result and result.get("status") == "timeout":
            rep.update(status="failed", stopped_because="the plan ran past its total max_minutes on Modal")
        return rep, self.cost(rep)

    def _mirror(self, volume, light: bool) -> None:
        """Copy the run's files from the volume: progress and logs while it runs, everything at the end."""
        prefix = f"runs/{self.run_dir.name}"
        try:
            entries = volume.listdir(prefix, recursive=True)
        except Exception:
            return
        for e in entries:
            if getattr(e.type, "name", str(e.type)) != "FILE":
                continue
            rel = Path(e.path).relative_to(prefix)
            if light and not (rel.name in ("progress.jsonl", "report.json", "log.txt", "result.json")):
                continue
            stamp = (getattr(e, "size", None), getattr(e, "mtime", None))
            if self._seen.get(e.path) == stamp and stamp != (None, None):
                continue                                 # unchanged since the last copy
            self._seen[e.path] = stamp
            target = self.run_dir / rel
            target.parent.mkdir(parents=True, exist_ok=True)
            try:
                target.write_bytes(b"".join(volume.read_file(e.path)))
            except Exception:
                pass

    def cancel(self) -> str:
        return cancel_call(self.call.object_id) if self.call else ""

    def cost(self, rep: dict) -> float:
        minutes = (time.time() - self.remote_started) / 60 if self.remote_started else 0.0
        return budget.rate_per_minute(self.cfg, self.plan) * (minutes + 0.5)
